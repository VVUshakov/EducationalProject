// Объявляем пространство имен для сервисов
namespace EducationalProject.Services
{
    // Класс Кодировщик имени, наследуется от BaseService
    public class NameEncoder : BaseService
    {
        // Реализуем свойство Name
        public override string Name => "Кодировщик имени";

        // Реализуем метод Run()
        public override void Run()
        {
            // Очищаем экран и показываем заголовок
            ConsoleHelper.ClearAndShowHeader(Name);

            // Массив строк с описанием
            string[] infoLines = {
                "Программа демонстрирует различные методы кодирования текста:",
                "1. Алфавитные позиции (А=1, Б=2, ...)",
                "2. Азбука Морзе",
                "3. Простой шифр (позиция × 3)"
            };

            // Показываем информационный блок
            ConsoleHelper.ShowInfoBlock(DESCRIPTION_TITLE, infoLines);

            // Получаем имя от пользователя, приводим к верхнему регистру
            string name = InputValidator.GetValidText(
                ">>> Введите ваше имя: ",
                minLength: 1,        // Минимум 1 символ
                maxLength: 50        // Максимум 50 символов
            ).ToUpper();             // Преобразуем все буквы в заглавные

            // Показываем методы кодирования
            ShowEncodingMethods();

            // Получаем выбор метода (1, 2 или 3)
            int choice = InputValidator.GetValidMenuChoice(1, 3, ">>> Выберите метод кодирования (1-3): ");

            // Кодируем имя выбранным методом
            string encodedName = EncodeName(name, choice);

            // Показываем результат
            ShowResult(name, encodedName, choice);

            // Ждем нажатия клавиши
            ConsoleHelper.WaitForAnyKey(PRESS_ANY_KEY_TO_RETURN);
        }

        // Метод для показа методов кодирования
        private void ShowEncodingMethods()
        {
            // Массив с описанием методов
            string[] methods = {
                "Алфавитные позиции (А=1, Б=2, ...)",
                "Азбука Морзе",
                "Простой шифр (позиция × 3)"
            };

            // Показываем меню
            ConsoleHelper.ShowMenu("МЕТОДЫ КОДИРОВАНИЯ", methods);

            // Пустая строка
            Console.WriteLine();
        }

        // Метод для кодирования имени в зависимости от выбора
        private string EncodeName(string name, int methodChoice)
        {
            // Выражение switch - выбираем метод кодирования
            return methodChoice switch
            {
                1 => GetAlphabetCode(name),   // Метод 1: алфавитные позиции
                2 => GetMorseCode(name),      // Метод 2: азбука Морзе
                3 => GetCipherCode(name),     // Метод 3: простой шифр
                _ => GetAlphabetCode(name)    // По умолчанию: алфавитные позиции
            };
        }

        // Метод 1: Кодирование алфавитными позициями
        private string GetAlphabetCode(string name)
        {
            // Создаем список для хранения кодов
            List<string> codes = new List<string>();

            // Перебираем каждый символ в имени
            foreach(char c in name)  // Для каждого символа c в строке name
            {
                // Если символ - буква И русская буква
                if(char.IsLetter(c) && IsRussianLetter(c))
                {
                    // Вычисляем позицию в алфавите: код символа минус код 'А' плюс 1
                    int position = c - 'А' + 1;

                    // Добавляем позицию с ведущими нулями (двузначное число)
                    codes.Add($"{position:00}");
                }
                // Если символ - буква, но не русская
                else if(char.IsLetter(c))
                {
                    // Добавляем символ с вопросительным знаком
                    codes.Add($"{c}?");
                }
                // Если символ - пробел
                else if(char.IsWhiteSpace(c))
                {
                    // Добавляем "[ПРОБЕЛ]"
                    codes.Add("[ПРОБЕЛ]");
                }
                // Любой другой символ
                else
                {
                    // Добавляем как есть
                    codes.Add($"{c}");
                }
            }

            // Соединяем все коды через дефис
            return string.Join("-", codes);
        }

        // Метод 2: Кодирование азбукой Морзе
        private string GetMorseCode(string name)
        {
            // Создаем список для кодов Морзе
            List<string> codes = new List<string>();

            // Перебираем каждый символ
            foreach(char c in name)
            {
                // Если символ - буква
                if(char.IsLetter(c))
                {
                    // Получаем символ Морзе для буквы
                    string morseSymbol = GetMorseSymbol(c);

                    // Добавляем в список
                    codes.Add(morseSymbol);
                }
                // Если символ - пробел
                else if(char.IsWhiteSpace(c))
                {
                    // В азбуке Морзе пробел кодируется как "/"
                    codes.Add("/");
                }
                // Любой другой символ
                else
                {
                    // Добавляем как есть
                    codes.Add($"{c}");
                }
            }

            // Соединяем коды через пробел
            return string.Join(" ", codes);
        }

        // Метод для получения символа Морзе для буквы
        private string GetMorseSymbol(char c)
        {
            // Приводим букву к верхнему регистру
            char upperC = char.ToUpper(c);

            // Выражение switch - для каждой русской буквы свой код Морзе
            return upperC switch
            {
                'А' => ".-",      // А = точка-тире
                'Б' => "-...",    // Б = тире-точка-точка-точка
                'В' => ".--",     // В = точка-тире-тире
                'Г' => "--.",     // Г = тире-тире-точка
                'Д' => "-..",     // Д = тире-точка-точка
                'Е' => ".",       // Е = точка
                'Ё' => ".",       // Ё тоже точка (как Е)
                'Ж' => "...-",    // Ж = точка-точка-точка-тире
                'З' => "--..",    // З = тире-тире-точка-точка
                'И' => "..",      // И = точка-точка
                'Й' => ".---",    // Й = точка-тире-тире-тире
                'К' => "-.-",     // К = тире-точка-тире
                'Л' => ".-..",    // Л = точка-тире-точка-точка
                'М' => "--",      // М = тире-тире
                'Н' => "-.",      // Н = тире-точка
                'О' => "---",     // О = тире-тире-тире
                'П' => ".--.",    // П = точка-тире-тире-точка
                'Р' => ".-.",     // Р = точка-тире-точка
                'С' => "...",     // С = точка-точка-точка
                'Т' => "-",       // Т = тире
                'У' => "..-",     // У = точка-точка-тире
                'Ф' => "..-.",    // Ф = точка-точка-тире-точка
                'Х' => "....",    // Х = точка-точка-точка-точка
                'Ц' => "-.-.",    // Ц = тире-точка-тире-точка
                'Ч' => "---.",    // Ч = тире-тире-тире-точка
                'Ш' => "----",    // Ш = тире-тире-тире-тире
                'Щ' => "--.-",    // Щ = тире-тире-точка-тире
                'Ъ' => "--.--",   // Ъ = тире-тире-точка-тире-тире
                'Ы' => "-.--",    // Ы = тире-точка-тире-тире
                'Ь' => "-..-",    // Ь = тире-точка-точка-тире
                'Э' => "..-..",   // Э = точка-точка-тире-точка-точка
                'Ю' => "..--",    // Ю = точка-точка-тире-тире
                'Я' => ".-.-",    // Я = точка-тире-точка-тире
                _ => "?"          // Для не-русских букв - знак вопроса
            };
        }

        // Метод 3: Простой шифр (позиция × 3)
        private string GetCipherCode(string name)
        {
            // Создаем список для кодов
            List<string> codes = new List<string>();

            // Перебираем каждый символ
            foreach(char c in name)
            {
                // Если символ - буква И русская буква
                if(char.IsLetter(c) && IsRussianLetter(c))
                {
                    // Вычисляем: (позиция в алфавите) × 3
                    int encodedValue = (c - 'А' + 1) * 3;

                    // Добавляем трехзначное число (001, 002, ...)
                    codes.Add($"{encodedValue:000}");
                }
                // Если буква, но не русская
                else if(char.IsLetter(c))
                {
                    // Добавляем с вопросительным знаком
                    codes.Add($"{c}?");
                }
                // Если пробел
                else if(char.IsWhiteSpace(c))
                {
                    // Добавляем "[ПРОБЕЛ]"
                    codes.Add("[ПРОБЕЛ]");
                }
                // Любой другой символ
                else
                {
                    // Добавляем как есть
                    codes.Add($"{c}");
                }
            }

            // Соединяем коды через пробел
            return string.Join(" ", codes);
        }

        // Метод для проверки, является ли символ русской буквой
        private bool IsRussianLetter(char c)
        {
            // Проверяем: символ от 'А' до 'Я' ИЛИ от 'а' до 'я'
            return (c >= 'А' && c <= 'Я') || (c >= 'а' && c <= 'я');
        }

        // Метод для показа результата кодирования
        private void ShowResult(string originalName, string encodedName, int methodChoice)
        {
            // Определяем название метода по номеру
            string methodName = methodChoice switch
            {
                1 => "Алфавитные позиции",  // Если 1
                2 => "Азбука Морзе",        // Если 2
                3 => "Простой шифр",        // Если 3
                _ => "Неизвестный метод"    // Если другой номер
            };

            // Массив строк для вывода результата
            string[] resultLines = {
                $"Исходное имя: {originalName}",
                $"Метод кодирования: {methodName}",
                "",  // Пустая строка для разделения
                $"Закодированное имя:",
                $"  {encodedName}"
            };

            // Показываем результат в информационном блоке
            ConsoleHelper.ShowInfoBlock("РЕЗУЛЬТАТ КОДИРОВАНИЯ", resultLines);
        }
    }
}